def get_stack(label, project_type):
    if project_type == "website":
        return WEBSITE_STACKS.get(label, {})
    return DESKTOP_STACKS.get(label, {})


def get_design(sphere, project_type, answers_flat=None):
    """Базовые рекомендации по сфере, уточнённые ответами пользователя."""
    if project_type == "website":
        base = dict(WEBSITE_DESIGN.get(sphere, WEBSITE_DESIGN["other"]))
    else:
        base = dict(DESKTOP_DESIGN.get(sphere, DESKTOP_DESIGN["other"]))

    if not answers_flat:
        return base

    if project_type == "website":
        _apply_website_overrides(base, answers_flat)
    else:
        _apply_desktop_overrides(base, answers_flat)

    return base


def _user_text(answer):
    """Текст из ответа вида «да, есть свои цвета/шрифт» — иначе пусто."""
    if isinstance(answer, dict) and answer.get("value") == "yes":
        return answer.get("text", "")
    return ""


